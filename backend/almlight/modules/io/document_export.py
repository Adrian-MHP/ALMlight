"""Word (.docx) and PDF rendering of document snapshots, including Markdown descriptions.

Both renderers walk the same Markdown token stream (markdown-it-py): paragraphs, headings, bold/italic/code,
bullet and numbered lists, tables and code blocks.
"""

from __future__ import annotations

import io
import os
from html import escape
from typing import Any

from markdown_it import MarkdownIt

from almlight import __version__
from almlight.modules.io.document_snapshot import DocNode, DocSnapshot

_md = MarkdownIt("commonmark", {"html": False}).enable("table")


def _tokens(text: str):
    return _md.parse(text or "")


# ============================== Word ==========================================================


def render_docx(snap: DocSnapshot, *, include_fields: bool = True, include_links: bool = True) -> bytes:
    from docx import Document
    from docx.enum.text import WD_ALIGN_PARAGRAPH
    from docx.oxml import OxmlElement
    from docx.oxml.ns import qn
    from docx.shared import Pt, RGBColor

    doc = Document()
    styles = doc.styles
    styles["Normal"].font.name = "Calibri"
    styles["Normal"].font.size = Pt(10.5)
    root = snap.root
    section = doc.sections[0]
    header = section.header.paragraphs[0]
    header.text = f"{root.title} — {root.key} {root.version}"
    header.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    footer = section.footer.paragraphs[0]
    footer.text = f"{snap.project_key} · {snap.source} · generated by ALMlight {__version__}"
    footer.alignment = WD_ALIGN_PARAGRAPH.CENTER

    doc.add_heading(root.title, level=0)
    meta = doc.add_table(rows=0, cols=2)
    meta.style = "Light List Accent 1"
    for label, value in (("Project", f"{snap.project_key} — {snap.project_name}"), ("Document", root.key),
                         ("Version", root.version), ("State", root.state or "–"), ("Content", snap.source),
                         ("Generated", snap.generated_at.strftime("%Y-%m-%d %H:%M UTC"))):
        cells = meta.add_row().cells
        cells[0].text, cells[1].text = label, value
    if root.description.strip():
        _md_to_docx(doc, root.description)

    # Table of contents (Word fills it when the document is opened / fields are updated).
    doc.add_paragraph("Contents", style="Heading 1")
    p = doc.add_paragraph()
    fld = OxmlElement("w:fldSimple")
    fld.set(qn("w:instr"), 'TOC \\o "1-3" \\h \\z \\u')
    run = OxmlElement("w:r")
    t = OxmlElement("w:t")
    t.text = "Right-click and choose “Update field” to refresh the table of contents."
    run.append(t)
    fld.append(run)
    p._p.append(fld)
    settings = doc.settings.element
    upd = OxmlElement("w:updateFields")
    upd.set(qn("w:val"), "true")
    settings.append(upd)

    grey = RGBColor(0x6B, 0x72, 0x80)

    def add_node(node: DocNode, depth: int) -> None:
        if node.is_heading:
            doc.add_heading(node.title, level=min(depth, 9))
        else:
            para = doc.add_paragraph()
            para.paragraph_format.space_before = Pt(8)
            para.paragraph_format.keep_with_next = True
            r = para.add_run(f"{node.key}  ")
            r.bold = True
            r.font.color.rgb = RGBColor(0x36, 0x4F, 0xC7)
            r = para.add_run(node.title)
            r.bold = True
            r = para.add_run(f"   {node.type_label} · {node.state or '–'} · {node.version}")
            r.font.size = Pt(8.5)
            r.font.color.rgb = grey
            if node.description.strip():
                _md_to_docx(doc, node.description)
            if node.applicability:
                q = doc.add_paragraph()
                r = q.add_run(f"Applies to: {node.applicability}")
                r.italic = True
                r.font.size = Pt(9)
            if include_fields and node.fields:
                table = doc.add_table(rows=0, cols=2)
                table.style = "Light Grid Accent 1"
                for label, value in node.fields:
                    cells = table.add_row().cells
                    cells[0].text, cells[1].text = label, value
            if include_links and node.links:
                q = doc.add_paragraph()
                for i, (label, key, title) in enumerate(node.links):
                    r = q.add_run(("" if i == 0 else "\n") + f"{label}: {key} {title}")
                    r.font.size = Pt(9)
                    r.font.color.rgb = grey
        for child in node.children:
            add_node(child, depth + 1)

    for child in root.children:
        add_node(child, 1)
    buf = io.BytesIO()
    doc.save(buf)
    return buf.getvalue()


def _md_to_docx(doc: Any, text: str) -> None:
    from docx.shared import Pt

    tokens = _tokens(text)
    lists: list[str] = []
    i = 0
    while i < len(tokens):
        t = tokens[i]
        if t.type in ("bullet_list_open", "ordered_list_open"):
            lists.append("bullet" if t.type == "bullet_list_open" else "ordered")
        elif t.type in ("bullet_list_close", "ordered_list_close"):
            lists.pop()
        elif t.type == "heading_open":
            p = doc.add_paragraph()
            _inline_docx(p, tokens[i + 1].children or [], bold=True)
            i += 2
        elif t.type == "paragraph_open":
            style = None
            if lists:
                style = "List Bullet" if lists[-1] == "bullet" else "List Number"
            p = doc.add_paragraph(style=style)
            _inline_docx(p, tokens[i + 1].children or [])
            i += 2
        elif t.type in ("fence", "code_block"):
            p = doc.add_paragraph()
            r = p.add_run(t.content.rstrip("\n"))
            r.font.name = "Consolas"
            r.font.size = Pt(9)
        elif t.type == "table_open":
            rows: list[list[list[Any]]] = []
            j = i + 1
            while tokens[j].type != "table_close":
                if tokens[j].type == "tr_open":
                    rows.append([])
                elif tokens[j].type == "inline":
                    rows[-1].append(tokens[j].children or [])
                j += 1
            if rows:
                width = max(len(r) for r in rows)
                table = doc.add_table(rows=len(rows), cols=width)
                table.style = "Table Grid"
                for ri, row in enumerate(rows):
                    for ci, cell_tokens in enumerate(row):
                        cell_p = table.cell(ri, ci).paragraphs[0]
                        _inline_docx(cell_p, cell_tokens, bold=ri == 0)
            i = j
        i += 1


def _inline_docx(p: Any, children: list, bold: bool = False) -> None:
    state = {"b": bold, "i": False}
    for c in children:
        if c.type == "strong_open":
            state["b"] = True
        elif c.type == "strong_close":
            state["b"] = bold
        elif c.type == "em_open":
            state["i"] = True
        elif c.type == "em_close":
            state["i"] = False
        elif c.type in ("softbreak",):
            p.add_run(" ")
        elif c.type == "hardbreak":
            p.add_run().add_break()
        elif c.type == "code_inline":
            r = p.add_run(c.content)
            r.font.name = "Consolas"
        elif c.type == "text":
            r = p.add_run(c.content)
            r.bold, r.italic = state["b"], state["i"]


# ============================== PDF ===========================================================

_FONT = {"regular": "Helvetica", "bold": "Helvetica-Bold", "italic": "Helvetica-Oblique", "mono": "Courier"}
_FONT_DIRS = ("/usr/share/fonts/truetype/dejavu", "/usr/share/fonts/dejavu")


def _register_fonts() -> None:
    """Use DejaVu (full Unicode: ±, °, ≤, Ω, arrows) when installed; fall back to the PDF core fonts."""
    if _FONT["regular"] == "DejaVu":
        return
    from reportlab.lib.fonts import addMapping
    from reportlab.pdfbase import pdfmetrics
    from reportlab.pdfbase.ttfonts import TTFont

    for d in _FONT_DIRS:
        files = {"DejaVu": "DejaVuSans.ttf", "DejaVu-Bold": "DejaVuSans-Bold.ttf",
                 "DejaVu-Oblique": "DejaVuSans-Oblique.ttf", "DejaVu-Mono": "DejaVuSansMono.ttf"}
        if all(os.path.exists(os.path.join(d, f)) for f in files.values()):
            for name, f in files.items():
                pdfmetrics.registerFont(TTFont(name, os.path.join(d, f)))
            addMapping("DejaVu", 0, 0, "DejaVu")
            addMapping("DejaVu", 1, 0, "DejaVu-Bold")
            addMapping("DejaVu", 0, 1, "DejaVu-Oblique")
            addMapping("DejaVu", 1, 1, "DejaVu-Bold")
            _FONT.update(regular="DejaVu", bold="DejaVu-Bold", italic="DejaVu-Oblique", mono="DejaVu-Mono")
            return


def render_pdf(snap: DocSnapshot, *, include_fields: bool = True, include_links: bool = True) -> bytes:
    from reportlab.lib import colors
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
    from reportlab.lib.units import mm
    from reportlab.platypus import (
        KeepTogether,
        PageBreak,
        Paragraph,
        SimpleDocTemplate,
        Spacer,
        Table,
        TableStyle,
    )
    from reportlab.platypus.tableofcontents import TableOfContents

    _register_fonts()
    base = getSampleStyleSheet()
    f = _FONT
    s = {
        "title": ParagraphStyle("DocTitle", parent=base["Title"], fontName=f["bold"], fontSize=22, leading=26),
        "h1": ParagraphStyle("H1", parent=base["Heading1"], fontName=f["bold"], fontSize=15, spaceBefore=12),
        "h2": ParagraphStyle("H2", parent=base["Heading2"], fontName=f["bold"], fontSize=13, spaceBefore=10),
        "h3": ParagraphStyle("H3", parent=base["Heading3"], fontName=f["bold"], fontSize=11.5, spaceBefore=8),
        "body": ParagraphStyle("Body", parent=base["BodyText"], fontName=f["regular"], fontSize=9.5, leading=13),
        "req": ParagraphStyle("Req", parent=base["BodyText"], fontName=f["bold"], fontSize=10, leading=13,
                              spaceBefore=8, textColor=colors.HexColor("#1f2937")),
        "meta": ParagraphStyle("Meta", parent=base["BodyText"], fontName=f["regular"], fontSize=8, leading=10,
                               textColor=colors.HexColor("#6b7280")),
        "code": ParagraphStyle("Code", parent=base["Code"], fontName=f["mono"], fontSize=8),
        "cell": ParagraphStyle("Cell", parent=base["BodyText"], fontName=f["regular"], fontSize=8.5, leading=10.5),
    }
    root = snap.root

    class Doc(SimpleDocTemplate):
        def afterFlowable(self, flowable: Any) -> None:  # noqa: N802 — ReportLab hook name
            if isinstance(flowable, Paragraph) and getattr(flowable, "_toc_level", None) is not None:
                self.notify("TOCEntry", (flowable._toc_level, flowable.getPlainText(), self.page))

    def on_page(canvas: Any, doc_: Any) -> None:
        canvas.saveState()
        canvas.setFont(f["regular"], 8)
        canvas.setFillColor(colors.HexColor("#6b7280"))
        canvas.drawString(18 * mm, 287 * mm, f"{root.title} — {root.key} {root.version}")
        canvas.drawRightString(192 * mm, 10 * mm, f"{snap.project_key} · {snap.source} · page {doc_.page}")
        canvas.restoreState()

    story: list[Any] = [Paragraph(escape(root.title), s["title"])]
    meta_rows = [["Project", f"{snap.project_key} — {snap.project_name}"], ["Document", root.key],
                 ["Version", root.version], ["State", root.state or "–"], ["Content", snap.source],
                 ["Generated", snap.generated_at.strftime("%Y-%m-%d %H:%M UTC") + f" · ALMlight {__version__}"]]
    t = Table([[Paragraph(escape(a), s["cell"]), Paragraph(escape(b), s["cell"])] for a, b in meta_rows],
              colWidths=[35 * mm, 125 * mm])
    t.setStyle(TableStyle([("LINEBELOW", (0, 0), (-1, -1), 0.25, colors.HexColor("#d1d5db")),
                           ("VALIGN", (0, 0), (-1, -1), "TOP")]))
    story += [Spacer(1, 6 * mm), t, Spacer(1, 4 * mm)]
    if root.description.strip():
        story += _md_to_flowables(root.description, s)
    toc = TableOfContents()
    toc.levelStyles = [ParagraphStyle("TOC1", fontName=f["bold"], fontSize=10, leftIndent=0, leading=14),
                       ParagraphStyle("TOC2", fontName=f["regular"], fontSize=9.5, leftIndent=12, leading=13),
                       ParagraphStyle("TOC3", fontName=f["regular"], fontSize=9, leftIndent=24, leading=12)]
    story += [Spacer(1, 4 * mm), Paragraph("Contents", s["h1"]), toc, PageBreak()]

    def heading(text: str, depth: int) -> Paragraph:
        para = Paragraph(escape(text), s[f"h{min(depth, 3)}"])
        para._toc_level = min(depth, 3) - 1
        return para

    def add_node(node: DocNode, depth: int) -> None:
        if node.is_heading:
            story.append(heading(node.title, depth))
        else:
            block: list[Any] = [
                Paragraph(f'<font color="#364fc7">{escape(node.key)}</font>&nbsp;&nbsp;{escape(node.title)}', s["req"]),
                Paragraph(escape(f"{node.type_label} · {node.state or '–'} · {node.version}"), s["meta"]),
            ]
            block += _md_to_flowables(node.description, s)
            if node.applicability:
                block.append(Paragraph(f"<i>Applies to: {escape(node.applicability)}</i>", s["meta"]))
            if include_fields and node.fields:
                ft = Table([[Paragraph(escape(a), s["cell"]), Paragraph(escape(b), s["cell"])] for a, b in node.fields],
                           colWidths=[45 * mm, 115 * mm], hAlign="LEFT")
                ft.setStyle(TableStyle([("GRID", (0, 0), (-1, -1), 0.25, colors.HexColor("#d1d5db")),
                                        ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#f3f4f6"))]))
                block += [Spacer(1, 2), ft]
            if include_links and node.links:
                block.append(Paragraph("<br/>".join(escape(f"{lab}: {k} {ti}") for lab, k, ti in node.links),
                                       s["meta"]))
            story.append(KeepTogether(block[:3]))
            story.extend(block[3:])
        for child in node.children:
            add_node(child, depth + 1)

    for child in root.children:
        add_node(child, 1)
    buf = io.BytesIO()
    doc = Doc(buf, pagesize=A4, leftMargin=18 * mm, rightMargin=18 * mm, topMargin=18 * mm, bottomMargin=16 * mm,
              title=root.title, author="ALMlight", subject=f"{snap.project_key} {root.key}")
    doc.multiBuild(story, onFirstPage=on_page, onLaterPages=on_page)
    return buf.getvalue()


def _inline_rl(children: list) -> str:
    out: list[str] = []
    for c in children:
        if c.type == "strong_open":
            out.append("<b>")
        elif c.type == "strong_close":
            out.append("</b>")
        elif c.type == "em_open":
            out.append("<i>")
        elif c.type == "em_close":
            out.append("</i>")
        elif c.type == "softbreak":
            out.append(" ")
        elif c.type == "hardbreak":
            out.append("<br/>")
        elif c.type == "code_inline":
            out.append(f'<font face="{_FONT["mono"]}">{escape(c.content)}</font>')
        elif c.type == "text":
            out.append(escape(c.content))
    return "".join(out)


def _md_to_flowables(text: str, s: dict[str, Any]) -> list[Any]:
    from reportlab.lib import colors
    from reportlab.platypus import ListFlowable, ListItem, Paragraph, Preformatted, Table, TableStyle

    tokens = _tokens(text)
    out: list[Any] = []
    stack: list[tuple[str, list[Any]]] = []
    i = 0

    def emit(flowable: Any) -> None:
        (stack[-1][1] if stack else out).append(flowable)

    while i < len(tokens):
        t = tokens[i]
        if t.type in ("bullet_list_open", "ordered_list_open"):
            stack.append(("bullet" if t.type == "bullet_list_open" else "1", []))
        elif t.type in ("bullet_list_close", "ordered_list_close"):
            kind, items = stack.pop()
            emit(ListFlowable([ListItem(x, leftIndent=12) for x in items], bulletType=kind, leftIndent=12,
                              bulletFontSize=8))
        elif t.type == "heading_open":
            emit(Paragraph(f"<b>{_inline_rl(tokens[i + 1].children or [])}</b>", s["body"]))
            i += 2
        elif t.type == "paragraph_open":
            emit(Paragraph(_inline_rl(tokens[i + 1].children or []), s["body"]))
            i += 2
        elif t.type in ("fence", "code_block"):
            emit(Preformatted(t.content.rstrip("\n"), s["code"]))
        elif t.type == "table_open":
            rows: list[list[Any]] = []
            j = i + 1
            while tokens[j].type != "table_close":
                if tokens[j].type == "tr_open":
                    rows.append([])
                elif tokens[j].type == "inline":
                    rows[-1].append(Paragraph(_inline_rl(tokens[j].children or []), s["cell"]))
                j += 1
            if rows:
                width = max(len(r) for r in rows)
                rows = [r + [""] * (width - len(r)) for r in rows]
                tbl = Table(rows, hAlign="LEFT", repeatRows=1)
                tbl.setStyle(TableStyle([("GRID", (0, 0), (-1, -1), 0.25, colors.HexColor("#9ca3af")),
                                         ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#f3f4f6"))]))
                emit(tbl)
            i = j
        i += 1
    return out
