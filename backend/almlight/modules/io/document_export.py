"""Word (.docx) and PDF rendering of document snapshots.

Item texts are rich text (canonical HTML); both renderers use the shared block model in ``rich_render`` —
paragraphs, headings, marks, links, item references, lists, quotes, code, tables (with spans) and images.
"""

from __future__ import annotations

import io
import os
from html import escape
from typing import Any

from almlight import PRODUCT, __version__
from almlight.core import i18n
from almlight.modules.io.document_snapshot import DocNode, DocSnapshot
from almlight.modules.io.rich_render import DocxWriter, pdf_flowables

# ============================== Word ==========================================================


def _meta_rows(snap: DocSnapshot, with_product: bool = False) -> list[tuple[str, str]]:
    lab = lambda en: i18n.t(snap.locale, en)  # noqa: E731
    generated = snap.generated_at.strftime("%Y-%m-%d %H:%M UTC")
    if with_product:
        generated += f" · {PRODUCT} {__version__}"
    return [(lab("Project"), f"{snap.project_key} — {snap.project_name}"), (lab("Document"), snap.root.key),
            (lab("Version"), snap.root.version), (lab("State"), snap.root.state or "–"), (lab("Content"), snap.source),
            (lab("Generated"), generated)]


def template_values(snap: DocSnapshot, author: str | None = None) -> dict[str, str]:
    root = snap.root
    variant = snap.variant or {}
    return {"title": root.title, "key": root.key, "version": root.version, "state": root.state or "–",
            "project": snap.project_key, "project_name": snap.project_name, "source": snap.source,
            "variant": f"{variant['key']} {variant['title']}" if variant else i18n.t(snap.locale, "all variants"),
            "date": snap.generated_at.strftime("%Y-%m-%d"), "author": author or "", "product": PRODUCT}


def render_docx(snap: DocSnapshot, *, include_fields: bool = True, include_links: bool = True,
                roundtrip: str | None = None, template: bytes | None = None, author: str | None = None) -> bytes:
    """Word export. ``roundtrip`` = ``edit`` or ``comments`` prepares the file for the Word round trip;
    ``template`` is a customer Word template (see ``word_template``) that replaces the standard layout."""
    from docx import Document
    from docx.enum.text import WD_ALIGN_PARAGRAPH
    from docx.oxml import OxmlElement
    from docx.oxml.ns import qn
    from docx.shared import Pt, RGBColor

    root = snap.root
    content_start = None
    if template is not None:
        from almlight.modules.io import word_template

        doc = word_template.open_template(template)
        word_template.ensure_styles(doc)
        word_template.fill(doc, template_values(snap, author))
        toc = word_template.marker(doc, "toc")
        if toc is not None:
            word_template.toc_field(toc)
        content_start = len(doc.element.body)
        writer = DocxWriter(doc)
        if root.description.strip():
            writer.write(doc, _parse(root.description))
    else:
        doc = Document()
        styles = doc.styles
        styles["Normal"].font.name = "Calibri"
        styles["Normal"].font.size = Pt(10.5)
        section = doc.sections[0]
        header = section.header.paragraphs[0]
        header.text = f"{root.title} — {root.key} {root.version}"
        header.alignment = WD_ALIGN_PARAGRAPH.RIGHT
        footer = section.footer.paragraphs[0]
        footer.text = f"{snap.project_key} · {snap.source} · " + i18n.t(
            snap.locale, "generated by {product}", product=f"{PRODUCT} {__version__}")
        footer.alignment = WD_ALIGN_PARAGRAPH.CENTER

        doc.add_heading(root.title, level=0)
        meta = doc.add_table(rows=0, cols=2)
        meta.style = "Light List Accent 1"
        for label, value in _meta_rows(snap):
            cells = meta.add_row().cells
            cells[0].text, cells[1].text = label, value
        writer = DocxWriter(doc)
        if root.description.strip():
            writer.write(doc, _parse(root.description))

        # Table of contents (Word fills it when the document is opened / fields are updated).
        doc.add_paragraph(i18n.t(snap.locale, "Contents"), style="Heading 1")
        p = doc.add_paragraph()
        fld = OxmlElement("w:fldSimple")
        fld.set(qn("w:instr"), 'TOC \\o "1-3" \\h \\z \\u')
        run = OxmlElement("w:r")
        t = OxmlElement("w:t")
        t.text = i18n.t(snap.locale, "Right-click and choose “Update field” to refresh the table of contents.")
        run.append(t)
        fld.append(run)
        p._p.append(fld)
    settings = doc.settings.element
    upd = OxmlElement("w:updateFields")
    upd.set(qn("w:val"), "true")
    _insert_setting(settings, upd, before=("w:hdrShapeDefaults", "w:footnotePr", "w:endnotePr", "w:compat",
                                           "w:docVars", "w:rsids"))
    if roundtrip:
        from almlight.modules.documents.word_roundtrip import identifier

        props = doc.core_properties
        props.identifier = identifier(snap.project_key, root.key)
        props.keywords = "almlight-roundtrip"
        props.title = root.title
        props.subject = f"{root.key} {root.version} — round trip ({roundtrip})"
        if roundtrip == "comments":
            prot = OxmlElement("w:documentProtection")
            prot.set(qn("w:edit"), "comments")
            prot.set(qn("w:enforcement"), "1")
            _insert_setting(settings, prot, before=(
                "w:autoFormatOverride", "w:styleLockTheme", "w:styleLockQFSet", "w:defaultTabStop",
                "w:autoHyphenation", "w:characterSpacingControl", "w:compat", "w:rsids"))
        hint = doc.add_paragraph()
        hr = hint.add_run(i18n.t(snap.locale, "Review copy for {product} round trip — ", product=PRODUCT) + i18n.t(
            snap.locale, "edit text only inside the marked fields; add comments anywhere. Do not delete the fields."
            if roundtrip == "edit" else "add comments anywhere; the text is protected."))
        hr.italic = True
        hr.font.size = Pt(9)

    def tag_of(node: DocNode, part: str) -> str:
        return f"alm:{node.item_id}:{node.version_no}:{part}"

    grey = RGBColor(0x6B, 0x72, 0x80)

    def add_node(node: DocNode, depth: int) -> None:
        if node.is_heading:
            if roundtrip:
                hp = doc.add_paragraph(style=f"Heading {min(depth, 9)}")
                if node.number and node.display_title != node.title:
                    hp.add_run(f"{node.number} ")
                _inline_sdt(hp, node.title, tag_of(node, "title"), f"{node.key} title")
            else:
                doc.add_heading(node.display_title, level=min(depth, 9))
        else:
            para = doc.add_paragraph()
            para.paragraph_format.space_before = Pt(8)
            para.paragraph_format.keep_with_next = True
            r = para.add_run(f"{node.key}  ")
            r.bold = True
            r.font.color.rgb = RGBColor(0x36, 0x4F, 0xC7)
            if roundtrip:
                _inline_sdt(para, node.title, tag_of(node, "title"), f"{node.key} title", bold=True)
            else:
                r = para.add_run(node.title)
                r.bold = True
            r = para.add_run(f"   {node.type_label} · {node.state or '–'} · {node.version}")
            r.font.size = Pt(8.5)
            r.font.color.rgb = grey
            if roundtrip:
                start = len(doc.element.body)
                if node.raw_description.strip():
                    writer.write(doc, _parse(node.raw_description))
                else:
                    doc.add_paragraph()
                _wrap_blocks(doc, start, tag_of(node, "desc"), f"{node.key} text")
                extra = node.description[len(node.raw_description):].strip()
                if extra:
                    writer.write(doc, _parse(extra))
            elif node.description.strip():
                writer.write(doc, _parse(node.description))
            if node.applicability:
                q = doc.add_paragraph()
                r = q.add_run(i18n.t(snap.locale, "Applies to: {expr}", expr=node.applicability))
                r.italic = True
                r.font.size = Pt(9)
            if include_fields and node.fields:
                table = doc.add_table(rows=0, cols=2)
                table.style = "Light Grid Accent 1"
                for label, value in node.fields:
                    cells = table.add_row().cells
                    cells[0].text, cells[1].text = label, value
            if include_links and node.links:
                q = doc.add_paragraph()
                for i, (label, key, title) in enumerate(node.links):
                    r = q.add_run(("" if i == 0 else "\n") + f"{label}: {key} {title}")
                    r.font.size = Pt(9)
                    r.font.color.rgb = grey
        for child in node.children:
            add_node(child, depth + 1)

    for child in root.children:
        add_node(child, 1)
    if content_start is not None:
        from almlight.modules.io import word_template

        anchor = word_template.marker(doc, "content")
        if anchor is not None:
            word_template.move_before(doc, content_start, anchor)
    buf = io.BytesIO()
    doc.save(buf)
    return buf.getvalue()


def _insert_setting(settings: Any, el: Any, before: tuple[str, ...]) -> None:
    """Insert into settings.xml respecting the schema order Word insists on."""
    from docx.oxml.ns import qn

    for name in before:
        anchor = settings.find(qn(name))
        if anchor is not None:
            anchor.addprevious(el)
            return
    settings.append(el)


def _sdt(tag: str, alias: str) -> tuple[Any, Any]:
    from docx.oxml import OxmlElement
    from docx.oxml.ns import qn

    sdt = OxmlElement("w:sdt")
    pr = OxmlElement("w:sdtPr")
    a = OxmlElement("w:alias")
    a.set(qn("w:val"), alias)
    t = OxmlElement("w:tag")
    t.set(qn("w:val"), tag)
    lock = OxmlElement("w:lock")
    lock.set(qn("w:val"), "sdtLocked")
    pr.extend([a, t, lock])
    content = OxmlElement("w:sdtContent")
    sdt.extend([pr, content])
    return sdt, content


def _inline_sdt(paragraph: Any, text: str, tag: str, alias: str, bold: bool = False) -> None:
    run = paragraph.add_run(text)
    run.bold = bold or None
    r = run._r
    paragraph._p.remove(r)
    sdt, content = _sdt(tag, alias)
    content.append(r)
    paragraph._p.append(sdt)


def _wrap_blocks(doc: Any, start: int, tag: str, alias: str) -> None:
    """Move the block elements added since ``start`` (body length before) into a block-level content control."""
    body = doc.element.body
    children = list(body)
    new = children[start - 1:-1]  # new blocks sit before the final sectPr
    sdt, content = _sdt(tag, alias)
    for el in new:
        body.remove(el)
        content.append(el)
    body.insert(len(body) - 1, sdt)


def _parse(html: str) -> list:
    from almlight.core.richtext import parse_html

    return parse_html(html)


# ============================== PDF ===========================================================

_FONT = {"regular": "Helvetica", "bold": "Helvetica-Bold", "italic": "Helvetica-Oblique", "mono": "Courier"}
_FONT_DIRS = ("/usr/share/fonts/truetype/dejavu", "/usr/share/fonts/dejavu")


def _register_fonts() -> None:
    """Use DejaVu (full Unicode: ±, °, ≤, Ω, arrows) when installed; fall back to the PDF core fonts."""
    if _FONT["regular"] == "DejaVu":
        return
    from reportlab.lib.fonts import addMapping
    from reportlab.pdfbase import pdfmetrics
    from reportlab.pdfbase.ttfonts import TTFont

    for d in _FONT_DIRS:
        files = {"DejaVu": "DejaVuSans.ttf", "DejaVu-Bold": "DejaVuSans-Bold.ttf",
                 "DejaVu-Oblique": "DejaVuSans-Oblique.ttf", "DejaVu-Mono": "DejaVuSansMono.ttf"}
        if all(os.path.exists(os.path.join(d, f)) for f in files.values()):
            for name, f in files.items():
                pdfmetrics.registerFont(TTFont(name, os.path.join(d, f)))
            addMapping("DejaVu", 0, 0, "DejaVu")
            addMapping("DejaVu", 1, 0, "DejaVu-Bold")
            addMapping("DejaVu", 0, 1, "DejaVu-Oblique")
            addMapping("DejaVu", 1, 1, "DejaVu-Bold")
            _FONT.update(regular="DejaVu", bold="DejaVu-Bold", italic="DejaVu-Oblique", mono="DejaVu-Mono")
            return


def render_pdf(snap: DocSnapshot, *, include_fields: bool = True, include_links: bool = True) -> bytes:
    from reportlab.lib import colors
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
    from reportlab.lib.units import mm
    from reportlab.platypus import (
        KeepTogether,
        PageBreak,
        Paragraph,
        SimpleDocTemplate,
        Spacer,
        Table,
        TableStyle,
    )
    from reportlab.platypus.tableofcontents import TableOfContents

    _register_fonts()
    base = getSampleStyleSheet()
    f = _FONT
    s = {
        "title": ParagraphStyle("DocTitle", parent=base["Title"], fontName=f["bold"], fontSize=22, leading=26),
        "h1": ParagraphStyle("H1", parent=base["Heading1"], fontName=f["bold"], fontSize=15, spaceBefore=12),
        "h2": ParagraphStyle("H2", parent=base["Heading2"], fontName=f["bold"], fontSize=13, spaceBefore=10),
        "h3": ParagraphStyle("H3", parent=base["Heading3"], fontName=f["bold"], fontSize=11.5, spaceBefore=8),
        "body": ParagraphStyle("Body", parent=base["BodyText"], fontName=f["regular"], fontSize=9.5, leading=13),
        "req": ParagraphStyle("Req", parent=base["BodyText"], fontName=f["bold"], fontSize=10, leading=13,
                              spaceBefore=8, textColor=colors.HexColor("#1f2937")),
        "meta": ParagraphStyle("Meta", parent=base["BodyText"], fontName=f["regular"], fontSize=8, leading=10,
                               textColor=colors.HexColor("#6b7280")),
        "code": ParagraphStyle("Code", parent=base["Code"], fontName=f["mono"], fontSize=8),
        "cell": ParagraphStyle("Cell", parent=base["BodyText"], fontName=f["regular"], fontSize=8.5, leading=10.5),
    }
    root = snap.root

    class Doc(SimpleDocTemplate):
        def afterFlowable(self, flowable: Any) -> None:  # noqa: N802 — ReportLab hook name
            if isinstance(flowable, Paragraph) and getattr(flowable, "_toc_level", None) is not None:
                self.notify("TOCEntry", (flowable._toc_level, flowable.getPlainText(), self.page))

    def on_page(canvas: Any, doc_: Any) -> None:
        canvas.saveState()
        canvas.setFont(f["regular"], 8)
        canvas.setFillColor(colors.HexColor("#6b7280"))
        canvas.drawString(18 * mm, 287 * mm, f"{root.title} — {root.key} {root.version}")
        canvas.drawRightString(192 * mm, 10 * mm, f"{snap.project_key} · {snap.source} · "
                               + i18n.t(snap.locale, "page {n}", n=doc_.page))
        canvas.restoreState()

    story: list[Any] = [Paragraph(escape(root.title), s["title"])]
    meta_rows = _meta_rows(snap, with_product=True)
    t = Table([[Paragraph(escape(a), s["cell"]), Paragraph(escape(b), s["cell"])] for a, b in meta_rows],
              colWidths=[35 * mm, 125 * mm])
    t.setStyle(TableStyle([("LINEBELOW", (0, 0), (-1, -1), 0.25, colors.HexColor("#d1d5db")),
                           ("VALIGN", (0, 0), (-1, -1), "TOP")]))
    story += [Spacer(1, 6 * mm), t, Spacer(1, 4 * mm)]
    text_width = 174 * mm
    if root.description.strip():
        story += pdf_flowables(root.description, s, max_width=text_width, mono=f["mono"])
    toc = TableOfContents()
    toc.levelStyles = [ParagraphStyle("TOC1", fontName=f["bold"], fontSize=10, leftIndent=0, leading=14),
                       ParagraphStyle("TOC2", fontName=f["regular"], fontSize=9.5, leftIndent=12, leading=13),
                       ParagraphStyle("TOC3", fontName=f["regular"], fontSize=9, leftIndent=24, leading=12)]
    story += [Spacer(1, 4 * mm), Paragraph(escape(i18n.t(snap.locale, "Contents")), s["h1"]), toc, PageBreak()]

    def heading(text: str, depth: int) -> Paragraph:
        para = Paragraph(escape(text), s[f"h{min(depth, 3)}"])
        para._toc_level = min(depth, 3) - 1
        return para

    def add_node(node: DocNode, depth: int) -> None:
        if node.is_heading:
            story.append(heading(node.display_title, depth))
        else:
            block: list[Any] = [
                Paragraph(f'<font color="#364fc7">{escape(node.key)}</font>&nbsp;&nbsp;{escape(node.title)}', s["req"]),
                Paragraph(escape(f"{node.type_label} · {node.state or '–'} · {node.version}"), s["meta"]),
            ]
            block += pdf_flowables(node.description, s, max_width=text_width, mono=f["mono"])
            if node.applicability:
                applies = i18n.t(snap.locale, "Applies to: {expr}", expr=node.applicability)
                block.append(Paragraph(f"<i>{escape(applies)}</i>", s["meta"]))
            if include_fields and node.fields:
                ft = Table([[Paragraph(escape(a), s["cell"]), Paragraph(escape(b), s["cell"])] for a, b in node.fields],
                           colWidths=[45 * mm, 115 * mm], hAlign="LEFT")
                ft.setStyle(TableStyle([("GRID", (0, 0), (-1, -1), 0.25, colors.HexColor("#d1d5db")),
                                        ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#f3f4f6"))]))
                block += [Spacer(1, 2), ft]
            if include_links and node.links:
                block.append(Paragraph("<br/>".join(escape(f"{lab}: {k} {ti}") for lab, k, ti in node.links),
                                       s["meta"]))
            story.append(KeepTogether(block[:3]))
            story.extend(block[3:])
        for child in node.children:
            add_node(child, depth + 1)

    for child in root.children:
        add_node(child, 1)
    buf = io.BytesIO()
    doc = Doc(buf, pagesize=A4, leftMargin=18 * mm, rightMargin=18 * mm, topMargin=18 * mm, bottomMargin=16 * mm,
              title=root.title, author=PRODUCT, subject=f"{snap.project_key} {root.key}")
    doc.multiBuild(story, onFirstPage=on_page, onLaterPages=on_page)
    return buf.getvalue()
